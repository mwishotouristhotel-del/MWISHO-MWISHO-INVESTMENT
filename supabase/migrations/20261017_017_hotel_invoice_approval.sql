create table public.hotel_invoice_requests (
 id uuid primary key default gen_random_uuid(),
 bill_id uuid not null references public.hotel_bills(id),
 organization_name text not null check(length(trim(organization_name)) between 2 and 200),
 kra_pin text not null check(length(trim(kra_pin)) between 5 and 30),
 purchase_order_number text,
 proposed_payment_method text not null check(proposed_payment_method in ('cash','mpesa','bank_transfer','other')),
 payment_terms text not null check(length(trim(payment_terms)) between 5 and 1000),
 status text not null default 'pending' check(status in ('pending','approved','rejected')),
 requested_by uuid not null references public.staff_profiles(user_id),
 requested_at timestamptz not null default now(),
 reviewed_by uuid references public.staff_profiles(user_id),
 reviewed_at timestamptz,
 review_note text,
 invoice_number bigint generated by default as identity,
 snapshot jsonb not null,
 constraint hotel_invoice_po_length check(purchase_order_number is null or length(purchase_order_number)<=100)
);
create unique index hotel_one_pending_invoice_per_bill on public.hotel_invoice_requests(bill_id) where status='pending';
create unique index hotel_one_approved_invoice_per_bill on public.hotel_invoice_requests(bill_id) where status='approved';
alter table public.hotel_invoice_requests enable row level security;
create or replace function public.hotel_request_invoice(p_bill uuid,p_organization text,p_kra_pin text,p_po text,p_payment_method text,p_terms text)
returns uuid language plpgsql security definer set search_path='' as $f$
declare v_bill public.hotel_bills%rowtype;v_snapshot jsonb;v_id uuid;
begin
 select * into v_bill from public.hotel_bills where id=p_bill for update;
 if not found or v_bill.status<>'open' or v_bill.cancellation_status='pending' then raise exception 'Bill unavailable for invoice';end if;
 if length(trim(coalesce(p_organization,'')))<2 or length(trim(coalesce(p_kra_pin,'')))<5 or length(trim(coalesce(p_terms,'')))<5 then raise exception 'Organization, KRA PIN and payment terms are required';end if;
 if p_payment_method not in ('cash','mpesa','bank_transfer','other') then raise exception 'Invalid proposed payment method';end if;
 if not exists(select 1 from public.staff_profiles s join public.staff_roles r on r.user_id=s.user_id and r.active and r.role='cashier' join public.departments d on d.id=r.department_id and d.name='Hotel' where s.user_id=auth.uid() and s.active) then raise exception 'Hotel cashier access required';end if;
 v_snapshot:=public.hotel_bill_preview(p_bill);
 if v_snapshot is null then raise exception 'No bill data';end if;
 if exists(select 1 from public.hotel_invoice_requests where bill_id=p_bill and status in ('pending','approved')) then raise exception 'Invoice already requested or approved';end if;
 insert into public.hotel_invoice_requests(bill_id,organization_name,kra_pin,purchase_order_number,proposed_payment_method,payment_terms,requested_by,snapshot)
 values(p_bill,trim(p_organization),upper(trim(p_kra_pin)),nullif(trim(coalesce(p_po,'')),''),p_payment_method,trim(p_terms),auth.uid(),v_snapshot)
 returning id into v_id;
 return v_id;
end $f$;
create or replace function public.hotel_invoice_queue()
returns jsonb language plpgsql stable security definer set search_path='' as $f$
declare v_manager boolean;v_cashier boolean;v_result jsonb;
begin
 select exists(select 1 from public.staff_profiles s join public.staff_roles r on r.user_id=s.user_id and r.active
 where s.user_id=auth.uid() and s.active and (r.role in ('director_admin','central_manager') or (r.role='department_manager' and r.department_id=(select id from public.departments where name='Hotel')))) into v_manager;
 select exists(select 1 from public.staff_profiles s join public.staff_roles r on r.user_id=s.user_id and r.active and r.role='cashier' where s.user_id=auth.uid() and s.active and r.department_id=(select id from public.departments where name='Hotel')) into v_cashier;
 if not v_manager and not v_cashier then raise exception 'Invoice access denied';end if;
 select coalesce(jsonb_agg(jsonb_build_object('id',i.id,'invoice_number',i.invoice_number,'bill_id',i.bill_id,'organization_name',i.organization_name,'kra_pin',i.kra_pin,'purchase_order_number',i.purchase_order_number,'proposed_payment_method',i.proposed_payment_method,'payment_terms',i.payment_terms,'status',i.status,'requested_at',i.requested_at,'reviewed_at',i.reviewed_at,'review_note',i.review_note,'snapshot',i.snapshot) order by i.requested_at desc),'[]'::jsonb) into v_result
 from public.hotel_invoice_requests i where (v_manager or i.requested_by=auth.uid()) and i.status in ('pending','approved','rejected');
 return v_result;
end $f$;
create or replace function public.hotel_review_invoice(p_request uuid,p_approve boolean,p_note text default null)
returns void language plpgsql security definer set search_path='' as $f$
declare v_invoice public.hotel_invoice_requests%rowtype;
begin
 if not exists(select 1 from public.staff_profiles s join public.staff_roles r on r.user_id=s.user_id and r.active
 where s.user_id=auth.uid() and s.active and (r.role in ('director_admin','central_manager') or (r.role='department_manager' and r.department_id=(select id from public.departments where name='Hotel')))) then raise exception 'Manager authorization required';end if;
 select * into v_invoice from public.hotel_invoice_requests where id=p_request for update;
 if not found or v_invoice.status<>'pending' then raise exception 'Invoice request not pending';end if;
 if v_invoice.requested_by=auth.uid() then raise exception 'Requestor cannot verify own invoice';end if;
 if not exists(select 1 from public.hotel_bills where id=v_invoice.bill_id and status='open' and cancellation_status<>'pending') then raise exception 'Bill is no longer eligible';end if;
 update public.hotel_invoice_requests set status=case when p_approve then 'approved' else 'rejected' end,reviewed_by=auth.uid(),reviewed_at=now(),review_note=nullif(trim(coalesce(p_note,'')),'') where id=p_request;
end $f$;
revoke all on function public.hotel_request_invoice(uuid,text,text,text,text,text) from public,anon;
revoke all on function public.hotel_invoice_queue() from public,anon;
revoke all on function public.hotel_review_invoice(uuid,boolean,text) from public,anon;
grant execute on function public.hotel_request_invoice(uuid,text,text,text,text,text),public.hotel_invoice_queue(),public.hotel_review_invoice(uuid,boolean,text) to authenticated;