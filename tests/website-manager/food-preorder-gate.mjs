import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
const html=await readFile('hotel/index.html','utf8');
const api=await readFile('supabase/functions/hotel-website-public/index.ts','utf8');
const d=new JSDOM(html).window.document;
assert(d.getElementById('openFoodMenu'));
assert(d.getElementById('mwFoodMenuDialog'));
assert(d.getElementById('mwMealDate'));
assert(d.getElementById('mwMealTime'));
assert(d.getElementById('mwFoodMpesaCode'),'transaction code is required for manual cashier verification');
assert(d.getElementById('mwFoodCheckout').textContent.includes('Verification'));
assert(html.includes('foodCart.set('));
assert(html.includes('Cashier/Admin verification is required before preparation'));
assert(api.includes("resource')==='food_menu'"));
assert(api.includes(".eq('preparation_area','kitchen')"));
assert(api.includes(".eq('hotel_stock_only',false)"));
assert(api.includes(".eq('active',true)"));
assert(api.includes("action==='submit_food_preorder'"),'server accepts pending review submissions');
assert(api.includes("status:'pending_verification'"),'customer code never marks the order paid');
assert(!api.includes("action==='pay_order'"),'no unverified payment action');
console.log('PASS: POS food menu filtering, customer cart, arrival controls and blocked payment/kitchen gate');
